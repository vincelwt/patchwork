// --- messages ---------------------------------------------------------------

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct SendMessage {
    #[serde(default)]
    pub body: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub parent_id: Option<Id>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub reply_to_id: Option<Id>,
    #[serde(default)]
    pub kind: Option<MessageKind>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub card: Option<MessageCard>,
    #[serde(default)]
    pub attachment_ids: Vec<Id>,
    /// Set by agents so the message is attributed to their run.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub run_id: Option<Id>,
    /// Optional, and generated by the sender. A client that retries a send it
    /// never got an answer to repeats this id, and the relay returns the
    /// message the first attempt stored instead of posting it twice.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub client_id: Option<Id>,
}

