// --- tasks ------------------------------------------------------------------

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct CreateTask {
    /// Optional: derived from the first line of `outcome` when blank.
    #[serde(default)]
    pub title: String,
    #[serde(default)]
    pub outcome: String,
    /// Immutable source context for the task discussion. Defaults to the
    /// outcome, or the title when the outcome is blank.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub initial_message: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub status: Option<TaskStatus>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub owner_id: Option<Id>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_channel_id: Option<Id>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub source_message_id: Option<Id>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub project_id: Option<Id>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub host_id: Option<Id>,
    /// `new_worktree` (default when a project is set), `existing_worktree`,
    /// `main_checkout`, or `none`.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub code_mode: Option<String>,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub existing_worktree_id: Option<Id>,
    /// Epoch millis, or 0 for no date.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub due_at: Option<i64>,
    /// Asking twice about the same thing makes one task: an open task with
    /// this key is returned instead of a second one being created.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub once_key: Option<String>,
    /// Confirm creation after the relay found a similar open or recent task.
    /// Exact `once_key` matches are still reused.
    #[serde(default)]
    pub allow_similar: bool,
    /// Files uploaded before the task exists. They become evidence on the
    /// immutable original request.
    #[serde(default)]
    pub attachment_ids: Vec<Id>,
    /// Start the owning agent immediately. Tasks assigned to an agent also
    /// start by default unless `status` is explicitly `planned`.
    #[serde(default)]
    pub start: bool,
}

